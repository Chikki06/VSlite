#!/usr/bin/env python3
"""Select D-combine runs from results/cislnet/experiments/tracking.csv.

Grouping (canonical):
  A — skip-attention ablations (coordatt, triplet, scse, gcblock, eca, simam)
  B — structure / capacity (half decoder, scconv, convnext, depthwise, pixelshuffle)
  C — color space (linear HE)
  IO — data-path only (fp16 on-disk IR); not used for D knobs

Legacy run tags ``b4_eca_*`` / ``b5_simam_*`` are attention (group A) despite the
``b`` prefix — the letter in the name is historical.

Selection metric: ``lpips_convnext_tcga`` (primary), then ``latency_ms_mean``.

With ``--top_k 2`` (default), writes the 2×2 cross product of top attentions ×
top structures (4 env files under ``d_combos/``). ``d1_env.sh`` is the best×best
combo for backward compatibility with ``d1_combine.sh``.
"""

from __future__ import annotations

import argparse
import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_CSV = ROOT / "results" / "cislnet" / "experiments" / "tracking.csv"
OUT_DIR = ROOT / "results" / "cislnet" / "experiments"
OUT_ENV = OUT_DIR / "d1_env.sh"
OUT_MD = OUT_DIR / "README.md"
OUT_COMBOS = OUT_DIR / "d_combos"
OUT_SELECTION = OUT_DIR / "d1_selection.md"

# Attention modules (group A). Includes legacy b4/b5 run-name prefixes.
ATTENTION_RUN_RE = re.compile(
    r"^(a[1-4]_|b4_eca|b5_simam|a5_eca|a6_simam)", re.I
)
# Structure / capacity (group B). Explicit allow-list — never treat attention as B.
STRUCTURE_RUN_RE = re.compile(
    r"^(b1_half|b2_scconv|b3_convnext|b6_depthwise|b7_pixelshuffle)", re.I
)
COLOR_RUN_RE = re.compile(r"^c1_", re.I)
IO_RUN_RE = re.compile(r"^fp16_", re.I)

ATTENTION_TYPES = frozenset(
    {"coordatt", "triplet", "scse", "gcblock", "eca", "simam", "ecanet"}
)


def _f(row, key):
    v = row.get(key, "")
    if v is None or v == "":
        return None
    try:
        return float(v)
    except Exception:
        return None


def _canonical_group(row: dict) -> str:
    """Infer A/B/C/IO from run name + knobs; prefer stored group when consistent."""
    run = str(row.get("run") or "")
    attn = str(row.get("attention") or "cbam").lower().strip()
    stored = str(row.get("group") or "").upper().strip()

    if IO_RUN_RE.match(run):
        return "IO"
    if COLOR_RUN_RE.match(run) or stored == "C":
        return "C"
    if ATTENTION_RUN_RE.match(run) or attn in ATTENTION_TYPES:
        # Attention-only runs always A (fixes legacy TRACK_GROUP=B on ECA/SimAM).
        return "A"
    if STRUCTURE_RUN_RE.match(run):
        return "B"
    if stored in ("A", "B", "C", "IO", "D"):
        return stored
    return stored or "B"


def _dedupe_last(rows: list[dict]) -> list[dict]:
    by_run: dict[str, dict] = {}
    for r in rows:
        by_run[str(r.get("run"))] = r
    return list(by_run.values())


def _rank_key(row: dict):
    """Lower ConvNeXt-LPIPS better; then lower latency."""
    lp = _f(row, "lpips_convnext_tcga")
    lat = _f(row, "latency_ms_mean")
    return (
        lp if lp is not None else 1e9,
        lat if lat is not None else 1e9,
    )


def _struct_knobs(pick_s: dict) -> dict:
    run = str(pick_s.get("run") or "")
    backbone = "resnet50"
    decoder_conv = "standard"
    width = "1.0"
    ndf = "64"
    color = "srgb"
    upsample_mode = "convtranspose"
    if "b1_" in run:
        width, ndf = "0.5", "32"
    elif "b2_" in run:
        decoder_conv = "scconv"
    elif "b3_" in run:
        backbone = "convnext_tiny"
    elif "b6_" in run:
        decoder_conv = "depthwise"
    elif "b7_" in run:
        upsample_mode = "pixelshuffle"
    elif "c1_" in run:
        color = "linear"
    return {
        "backbone": backbone,
        "decoder_conv": decoder_conv,
        "width": width,
        "ndf": ndf,
        "color": color,
        "upsample_mode": upsample_mode,
    }


def _combo_name(attention: str, knobs: dict) -> str:
    backbone = knobs["backbone"].replace("convnext_tiny", "convnext")
    name = f"d1_{backbone}_{attention}_c13"
    if knobs["color"] == "linear":
        name += "_lin"
    if knobs["decoder_conv"] == "scconv":
        name += "_scconv"
    if knobs["decoder_conv"] == "depthwise":
        name += "_dw"
    if knobs["upsample_mode"] == "pixelshuffle":
        name += "_ps"
    if knobs["width"] != "1.0":
        name += "_half"
    return name


def _env_text(name: str, attention: str, knobs: dict, pick_a: dict, pick_s: dict, rank: str) -> str:
    return f"""# Auto-generated by scripts/select_pareto_d1.py ({rank})
export NAME={name}
export ATTENTION_TYPE={attention}
export ENCODER_BACKBONE={knobs['backbone']}
export DECODER_CONV={knobs['decoder_conv']}
export DECODER_WIDTH_MULT={knobs['width']}
export UPSAMPLE_MODE={knobs['upsample_mode']}
export NDF={knobs['ndf']}
export HE_COLOR_SPACE={knobs['color']}
export TRACK_GROUP=D
export TRACK_NOTES="D {rank}: attn={pick_a.get('run')} + struct={pick_s.get('run')}"
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", type=str, default=str(DEFAULT_CSV))
    ap.add_argument("--out_env", type=str, default=str(OUT_ENV))
    ap.add_argument("--out_md", type=str, default=str(OUT_MD))
    ap.add_argument("--out_combos", type=str, default=str(OUT_COMBOS))
    ap.add_argument("--top_k", type=int, default=2, help="Top-K attentions × top-K structures")
    ap.add_argument(
        "--rewrite_tracking_groups",
        action="store_true",
        help="Rewrite tracking.csv group column to canonical A/B/C/IO (dedupe last).",
    )
    args = ap.parse_args()

    path = Path(args.csv)
    if not path.is_file():
        raise SystemExit(f"tracking csv missing: {path}")

    raw = list(csv.DictReader(path.open()))
    rows = _dedupe_last(raw)
    for r in rows:
        r["group"] = _canonical_group(r)

    if args.rewrite_tracking_groups:
        fieldnames = list(raw[0].keys()) if raw else []
        # Preserve column order; ensure group present
        if "group" not in fieldnames:
            fieldnames.insert(1, "group")
        with path.open("w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=fieldnames)
            w.writeheader()
            for r in rows:
                w.writerow({k: r.get(k, "") for k in fieldnames})
        print(f"rewrote {path} ({len(rows)} unique runs, canonical groups)")

    group_a = [r for r in rows if r["group"] == "A"]
    group_b = [r for r in rows if r["group"] == "B"]
    if not group_a:
        raise SystemExit("No group A (attention) rows after canonical grouping")
    if not group_b:
        raise SystemExit("No group B (structure) rows after canonical grouping")

    top_k = max(1, int(args.top_k))
    attn_ranked = sorted(group_a, key=_rank_key)[:top_k]
    struct_ranked = sorted(group_b, key=_rank_key)[:top_k]

    combos_dir = Path(args.out_combos)
    combos_dir.mkdir(parents=True, exist_ok=True)
    # Clear old combo envs
    for old in combos_dir.glob("*.sh"):
        old.unlink()

    combo_meta = []
    for i, pick_a in enumerate(attn_ranked, start=1):
        for j, pick_s in enumerate(struct_ranked, start=1):
            attention = str(pick_a.get("attention") or "cbam")
            knobs = _struct_knobs(pick_s)
            name = _combo_name(attention, knobs)
            rank = f"A{i}×B{j}"
            text = _env_text(name, attention, knobs, pick_a, pick_s, rank)
            env_path = combos_dir / f"{name}.sh"
            env_path.write_text(text)
            combo_meta.append(
                {
                    "rank": rank,
                    "name": name,
                    "env": env_path,
                    "attn_run": pick_a.get("run"),
                    "struct_run": pick_s.get("run"),
                    "attention": attention,
                    "lpips_a": _f(pick_a, "lpips_convnext_tcga"),
                    "lat_a": _f(pick_a, "latency_ms_mean"),
                    "lpips_s": _f(pick_s, "lpips_convnext_tcga"),
                    "lat_s": _f(pick_s, "latency_ms_mean"),
                    "knobs": knobs,
                }
            )
            print(text)
            print(f"wrote {env_path}")

    # Best×best → d1_env.sh
    best = combo_meta[0]
    Path(args.out_env).write_text(best["env"].read_text())
    print(f"wrote {args.out_env} (best×best = {best['name']})")

    # README + selection report
    lines = [
        "# CISLNet experiment tracking",
        "",
        "Central table: `tracking.csv`.",
        "",
        "## Grouping",
        "",
        "| Group | Meaning | Runs |",
        "|-------|---------|------|",
        "| **A** | Skip attention | a1–a4, b4_eca (A5), b5_simam (A6) |",
        "| **B** | Structure / capacity | b1 half, b2 scconv, b3 convnext, b6 depthwise, b7 pixelshuffle |",
        "| **C** | Color space | c1 linear |",
        "| **IO** | Data path only | fp16 IR (not a D knob) |",
        "",
        "D selection metric: **ConvNeXt-LPIPS** then latency. "
        f"Top-{top_k} attentions × top-{top_k} structures → `{combos_dir.name}/`.",
        "",
        "## D combo grid",
        "",
        "| Rank | Name | Attention run | Structure run |",
        "|------|------|---------------|---------------|",
    ]
    for c in combo_meta:
        lines.append(
            f"| {c['rank']} | `{c['name']}` | {c['attn_run']} "
            f"(lpips={c['lpips_a']:.6f}, {c['lat_a']:.1f}ms) | "
            f"{c['struct_run']} (lpips={c['lpips_s']:.6f}, {c['lat_s']:.1f}ms) |"
        )
    lines += [
        "",
        "Submit all:",
        "",
        "```bash",
        "bash jobs/cislnet/experiments/submit_d_combos.sh",
        "```",
        "",
    ]
    Path(args.out_md).write_text("\n".join(lines) + "\n")
    Path(OUT_SELECTION).write_text("\n".join(lines) + "\n")
    print(f"wrote {args.out_md}")
    print(f"wrote {OUT_SELECTION}")


if __name__ == "__main__":
    main()
